-- Auto-vínculo dinâmico: sempre que uma ferramenta_unidade for cadastrada/tiver o código
-- corrigido, tenta casar com algum item da checklist ainda sem vínculo.
create or replace function public.fn_auto_link_checklist_especifer()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.checklist_especifer_itens
  set catalogo_id = new.catalogo_id
  where catalogo_id is null and (codigo = new.codigo or codigo_alternativo = new.codigo);
  return new;
end; $$;
create trigger trg_auto_link_checklist_unidade
  after insert or update of codigo on public.ferramentas_unidade
  for each row execute function public.fn_auto_link_checklist_especifer();

-- Mesma ideia pro codigo_interno do catálogo (cobre casos futuros de estoque em pool).
create or replace function public.fn_auto_link_checklist_especifer_catalogo()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.codigo_interno is not null then
    update public.checklist_especifer_itens
    set catalogo_id = new.id
    where catalogo_id is null and (codigo = new.codigo_interno or codigo_alternativo = new.codigo_interno);
  end if;
  return new;
end; $$;
create trigger trg_auto_link_checklist_catalogo
  after insert or update of codigo_interno on public.ferramentas_catalogo
  for each row execute function public.fn_auto_link_checklist_especifer_catalogo();
