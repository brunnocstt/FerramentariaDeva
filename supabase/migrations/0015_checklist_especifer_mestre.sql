-- Lista mestre da checklist oficial "Programa de Verificação de Ferramentas IVECO" (Especifer),
-- 228 itens, extraída do relatório #188322358 (auditoria de Montes Claros, concluída 02/04/2026
-- pelo Fredson Santos). Até aqui o "% de obrigatórias" só olhava pro que JÁ estava marcado
-- obrigatoria=true no catálogo — não refletia os itens da checklist que nunca foram cadastrados.
-- Essa tabela vira a referência fixa (228 itens sempre), e o vínculo com o catálogo é dinâmico:
-- quando alguém cadastra uma ferramenta cujo código bate com um item ainda sem vínculo, o
-- trigger liga sozinho — não precisa de reprocessamento manual.

create table public.checklist_especifer_itens (
  id uuid primary key default gen_random_uuid(),
  ordem integer not null,
  codigo text not null,
  codigo_alternativo text,
  descricao text not null,
  catalogo_id uuid references public.ferramentas_catalogo(id),
  created_at timestamptz not null default now()
);
comment on table public.checklist_especifer_itens is
  'Lista fixa dos 228 itens da checklist oficial Especifer/Iveco (Programa de Verificação de Ferramentas). catalogo_id é preenchido automaticamente (trigger) ou manualmente por admin_geral quando o código bate com uma ferramenta cadastrada.';

alter table public.checklist_especifer_itens enable row level security;
create policy checklist_especifer_select on public.checklist_especifer_itens for select to authenticated using (true);
create policy checklist_especifer_update on public.checklist_especifer_itens for update to authenticated
  using (private.is_admin_geral()) with check (private.is_admin_geral());
grant select on public.checklist_especifer_itens to authenticated;
grant update (catalogo_id) on public.checklist_especifer_itens to authenticated;

